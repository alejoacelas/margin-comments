function currentIdentity(): PageIdentity | null {
  const canonical = document.querySelector<HTMLLinkElement>('link[rel~="canonical" i][href]');
  return pageIdentity(location.href, canonical?.href ?? null);
}

function hash(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36);
}

/**
 * The selected range, also when it's inside a web component: Chrome reports
 * such a selection retargeted to the shadow host (the range doesn't hold the
 * text that's selected); `getComposedRanges` with the open shadow roots gives
 * the real one. Null if it crosses a shadow boundary (a Range can't).
 */
function selectedRange(sel: Selection): Range | null {
  const range = sel.getRangeAt(0);
  const composed = (sel as Selection & { getComposedRanges?: (...args: unknown[]) => StaticRange[] }).getComposedRanges;
  if (typeof composed !== 'function') return range;
  const roots = openShadowRoots(document.documentElement);
  if (roots.length === 0) return range;
  let ranges: StaticRange[];
  try {
    ranges = composed.call(sel, { shadowRoots: roots });
  } catch {
    try {
      ranges = composed.call(sel, ...roots); // older signature
    } catch {
      return null;
    }
  }
  const r = ranges[0];
  if (!r || r.startContainer.getRootNode() !== r.endContainer.getRootNode()) return null;
  const out = document.createRange();
  out.setStart(r.startContainer, r.startOffset);
  out.setEnd(r.endContainer, r.endOffset);
  return out;
}

/** Open shadow roots under `root`, nested ones included. */
function openShadowRoots(root: Node): ShadowRoot[] {
  const out: ShadowRoot[] = [];
  const visit = (top: Node) => {
    const walker = document.createTreeWalker(top, NodeFilter.SHOW_ELEMENT);
    for (let el = walker.nextNode() as Element | null; el; el = walker.nextNode() as Element | null) {
      if (el.shadowRoot) {
        out.push(el.shadowRoot);
        visit(el.shadowRoot);
      }
    }
  };
  visit(root);
  return out;
}

function inEditable(node: Node | null): boolean {
  const el = node instanceof Element ? node : node?.parentElement;
  return !!el?.closest('input, textarea, select, [contenteditable=""], [contenteditable="true"], [contenteditable="plaintext-only"]');
}

/**
 * The element inside our (possibly closed) shadow root that an event is
 * really for: under the pointer for pointer events, else the focused one.
 */
function resolveInner(root: ShadowRoot, e: Event): Node | null {
  const inside = (n: Node | null | undefined): Node | null => (n && n !== root && root.contains(n) ? n : null);
  // Clicks generated by the keyboard (Enter/Space on a focused control) have
  // no pointer position (detail 0): they're for the focused element.
  if (e instanceof MouseEvent && !(e.type === 'click' && e.detail === 0)) {
    return inside(root.elementFromPoint(e.clientX, e.clientY)) ?? inside(root.activeElement);
  }
  if (typeof TouchEvent !== 'undefined' && e instanceof TouchEvent) {
    const t = e.changedTouches[0] ?? e.touches[0];
    if (t) return inside(root.elementFromPoint(t.clientX, t.clientY)) ?? inside(root.activeElement);
  }
  return inside(root.activeElement);
}

/** Line boxes of a range plus the right edge of the block it sits in. */
function boxOf(range: Range): AnchorBox | null {
  const rects = Array.from(range.getClientRects()).filter(r => r.width > 0 && r.height > 0);
  if (rects.length === 0) return null;
  let columnRight = Math.max(...rects.map(r => r.right));
  const start = range.startContainer instanceof Element ? range.startContainer : range.startContainer.parentElement;
  let block: Element | null = start;
  while (block && block !== document.body) {
    const display = getComputedStyle(block).display;
    if (display !== 'inline' && display !== 'contents') break;
    block = block.parentElement;
  }
  if (block && block !== document.body) {
    const br = block.getBoundingClientRect();
    if (br.width > 0 && br.right - columnRight < 600) columnRight = Math.max(columnRight, br.right);
  }
  return { rects, columnRight };
}

const sameKeys = (a: string[], b: string[]) => a.length === b.length && a.every((k, i) => k === b[i]);

