  constructor(identity: PageIdentity) {
    this.identity = identity;
    const ui: UiState = {
      sidebarOpen: false,
      sidebarFilter: 'open',
      activeThreadId: null,
      hoverThreadId: null,
      composer: null,
      adder: null,
      layoutTick: 0,
      toast: null,
    };
    this.store = new Store({
      user: null,
      config: null,
      connection: 'offline',
      loaded: false,
      loadError: null,
      threads: new Map(),
      ops: [],
      drafts: [],
      anchors: new Map(),
      pageKeys: identity.keys,
      pageUrl: identity.url,
      ui,
      invalidated: false,
    });

    // UI host: a <div> on <html> (outside <body>, so page text and text
    // offsets never include it), with its own shadow root.
    for (const old of document.querySelectorAll(HOST_SELECTOR)) old.remove();
    this.host = document.createElement('div');
    this.host.setAttribute('data-margin-comments', '');
    // Closed in production: page scripts can't reach into our UI (read the
    // account, drafts or comments, or drive the controls with synthetic
    // events). Test builds use an open root so Playwright can drive it.
    const shadow = this.host.attachShadow({ mode: __OPEN_SHADOW__ ? 'open' : 'closed' });
    try {
      const sheet = new CSSStyleSheet();
      sheet.replaceSync(CSS_TEXT);
      shadow.adoptedStyleSheets = [sheet];
    } catch {
      const style = document.createElement('style');
      style.textContent = CSS_TEXT;
      shadow.appendChild(style);
    }
    this.container = document.createElement('div');
    shadow.appendChild(this.container);
    // Clicks inside our UI activate normally but don't bubble out to the page
    // (see early.ts for why clicks aren't replayed like other events).
    for (const type of ['click', 'dblclick', 'auxclick']) this.host.addEventListener(type, e => e.stopPropagation());
    document.documentElement.appendChild(this.host);
    if (window.__marginCommentsShield) {
      window.__marginCommentsShield.host = this.host;
      window.__marginCommentsShield.resolve = e => resolveInner(shadow, e);
    }

    this.highlighter = new Highlighter(pageIsDark());
    this.anchors = new AnchorManager(
      () => document.body,
      node => node === this.host || this.host.contains(node),
      () => this.onAnchorsChanged(),
      () => this.onLayoutChange(),
    );

    this.port = new BackgroundPort(
      msg => this.onMessage(msg),
      () => this.teardown(),
      () => {
        this.reopenFields();
        this.flushDrafts();
      },
    );

    render(<App store={this.store} actions={this} />, this.container);
    this.store.subscribe(() => this.sync());
    this.listen();
    this.anchors.start();
    this.port.connect();
    this.port.setHello(identity.keys, identity.url, this.instanceId);
    this.pendingOpen = threadIdFromUrl(location.href);
    this.lastLinkedThread = this.pendingOpen;
    this.urlTimer = setInterval(() => this.checkUrl(), 1000);
    void this.loadFonts();
    if (location.origin === API_ORIGIN && location.pathname === '/auth/verify') void this.handleVerifyPage();
  }

